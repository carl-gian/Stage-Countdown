// Generates src/components/stage/SceneArt.tsx from the approved mockup (docs/mockups/redesign.html).
// The mockup draws its three scenes with small builder functions and a seeded random; this runs that exact code once
// and writes the result out as fixed JSX, so the app shows the same art with no randomness at runtime.
// Run: node scripts/gen-scenes.mjs   (only needed if the scenes in the mockup change)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'docs/mockups/redesign.html'), 'utf8');
const start = html.indexOf('// A seeded random');
const end = html.indexOf('// ---------- Ring ticks');
if (start < 0 || end < 0) throw new Error('Scene builder code not found in the mockup');

const out = {};
const document = { getElementById: (id) => ({ set innerHTML(v) { out[id] = v; } }) };
new Function('document', html.slice(start, end))(document);

const round = (s) => s.replace(/-?\d+\.\d{3,}/g, (n) => String(Math.round(parseFloat(n) * 100) / 100));

function toJsx(markup) {
  return round(markup)
    .replace(/\sclass="/g, ' className="')
    .replace(/\s(stroke|font)-([a-z]+)=/g, (_, a, b) => ` ${a}${b[0].toUpperCase()}${b.slice(1)}=`)
    .replace(/style="--d:(-?[\d.]+)s;--delay:(-?[\d.]+)s"/g, (_, d, delay) => `style={a(${+d}${+delay ? `, ${+delay}` : ''})}`)
    .replace(/>\s*</g, '>\n<')
    .trim()
    .split('\n')
    .map((l) => `      ${l.trim()}`)
    .join('\n');
}

const scene = (name, id) => `function ${name}() {
  return (
    <>
${toJsx(out[id])}
    </>
  );
}
`;

const file = `// GENERATED by scripts/gen-scenes.mjs from docs/mockups/redesign.html: do not edit by hand.
// Original artwork, drawn in code. Colours come from the scene palettes in src/styles/stage.css (data-scene / data-mode).
import type { CSSProperties } from 'react';
import type { SceneName } from '@/types';

/** A moving piece: its animation length and start offset, slowed down by --speed (see stage.css). */
const a = (d: number, delay = 0) => ({ '--d': \`\${d}s\`, '--delay': \`\${delay}s\` }) as CSSProperties;

${scene('Mountains', 'scMountains')}
${scene('Meadow', 'scMeadow')}
${scene('Lake', 'scLake')}
const SCENES = { mountains: Mountains, meadow: Meadow, lake: Lake };

/** One of the three nature scenes, filling its box (cropped, never stretched). */
export default function SceneArt({ scene }: { scene: SceneName }) {
  const Scene = SCENES[scene] ?? Mountains;
  return (
    <svg className="cd-scene" viewBox="0 0 1600 900" preserveAspectRatio="xMidYMid slice" aria-hidden="true">
      <Scene />
    </svg>
  );
}
`;

writeFileSync(join(root, 'src/components/stage/SceneArt.tsx'), file);
console.log('SceneArt.tsx written:', Object.keys(out).join(', '), `${file.length} chars`);
